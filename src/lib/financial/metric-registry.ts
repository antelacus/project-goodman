function normalizeName(input: string): string {
  return input
    .replace(/\s+/g, '')
    .replace(/[：:]/g, '：')
    .replace(/^(一、|二、|三、|四、|五、|六、|七、|八、|九、|十、)/, '')
    .replace(/^[（(][一二三四五六七八九十][）)]/, '') // Handle both Chinese （） and English ()
    .replace(/^\d+\./, '')
    .replace(/^(其中：|加：|减：)/, '')
    .replace(/金额$/, '')
    .replace(/[（(][^）)]*[）)]$/, ''); // Remove trailing parenthetical notes - both Chinese （） and English ()
}

const ALIAS_TO_KEY = (() => {
  const map = new Map<string, string>();
  for (const metric of METRICS) {
    const allAliases = [metric.label, metric.key, ...metric.aliases];
    for (const alias of allAliases) {
      map.set(normalizeName(alias), metric.key);
    }
  }
  return map;
})();

export function resolveMetricKey(rawName: string): string | undefined {
  return ALIAS_TO_KEY.get(normalizeName(rawName));
}

export function getMetricDisplayName(key: string): string | undefined {
  return DISPLAY_BY_KEY.get(key);
}

export function getAllMetricKeys(): string[] {
  return Array.from(new Set(METRICS.map((metric) => metric.key)));
}

export function getMetricDefinitions(): MetricDefinition[] {
  return [...METRICS];
}

